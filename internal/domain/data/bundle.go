package data

import "context"

// FieldValues — результат одного успешного вызова Bundle.Fetch: значения
// каноничных полей, проиндексированные по id. Конкретный Go-тип значения
// зависит от поля и описан в каталоге каноничных полей; потребитель
// достаёт значения узкими геттерами с проверкой типа.
//
// Реализация Bundle обязана положить в FieldValues все поля, объявленные
// в Fields(); отсутствие поля — баг реализации.
type FieldValues map[string]any

// Bundle — атомарная группа полей одного провайдера, которую источник
// умеет отдать одним вызовом. Реализация решает, как именно достать
// данные (HTTP, кеш, локальный файл); для domain важен только контракт.
//
// Bundle знает только собственный идентификатор внутри своего источника;
// привязка к провайдеру задаётся при регистрации в реестре (см. Provider
// и Registrar).
type Bundle interface {
	// BundleID — стабильный идентификатор bundle внутри провайдера.
	BundleID() string

	// Fields — каноничные поля, которые bundle обязуется заполнить
	// при успешном Fetch.
	Fields() []FieldDescriptor

	// Fetch достаёт значения для тикера.
	//
	// Возможные ошибки:
	//   - sentinel-ошибка «нет данных» конкретного агрегата —
	//     для bundles карточки эмитента это company.ErrNotFound;
	//   - обёрнутая через fmt.Errorf ошибка сети, HTTP или разбора
	//     ответа провайдера — во всех остальных случаях.
	Fetch(ctx context.Context, ticker string) (FieldValues, error)
}
