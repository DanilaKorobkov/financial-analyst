package company

// StockShare — количество выпущенных акций эмитента на дату среза.
// Запись привязана к конкретному тикеру: обыкновенные (`SBER`) и
// привилегированные (`SBERP`) акции выпускаются отдельными записями.
type StockShare struct {
	// Ticker — тикер выпуска, к которому относится запись.
	Ticker string

	// Period — дата среза.
	Period StockPeriod

	// Num — количество акций (в штуках).
	Num int64
}
