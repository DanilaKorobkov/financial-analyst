package company

// StockPeriod — value-объект отчётного периода записи карточки эмитента.
// Используется секциями, где данные представляют ряд по отчётным датам:
// мультипликаторы, отчётность, операционные метрики, акционеры, выпуски акций.
//
// Frequency и Standard — гранулярность периода и стандарт отчётности соответственно;
// нулевое значение каждого поля означает «не определено» (см. enums.go).
type StockPeriod struct {
	// Year — финансовый год записи.
	Year int

	// Month — месяц окончания периода (12 для годового периода).
	Month int

	// Frequency — гранулярность периода (год, квартал, полугодие, YTM).
	Frequency StockPeriodFrequency

	// Standard — стандарт отчётности записи (МСФО, РСБУ, GAAP).
	Standard ReportStandard
}
